"""Create .env for the LIVE run (real Instagram account, real Meta business portfolio).

Only non-secret settings go into .env. Instagram passwords and backup codes are stored
by a human in a password manager / vault; the app records references only
(VAULT_BACKEND=reference_only).

    python -m scripts.make_live_env --meta-business-id 1234567890 [--company-email-domain testco.example] \
        --vault-scheme bw --candidate-provided

COMPANY_EMAIL_DOMAINS must list domains the company controls. A consumer domain such as
gmail.com is refused: listing it would make the audit treat every address there as
company-controlled. If only a personal-provider mailbox exists, omit the option and record
the mailbox as ``personal_provider_substitute`` in the email task; the audit then flags it.
"""

from __future__ import annotations

import argparse
import re
import secrets
from pathlib import Path

from app.config import CONSUMER_MAIL_DOMAINS

TEMPLATE = """# LIVE RUN CONFIGURATION - generated by scripts/make_live_env.py. Never commit this file.
# Contains no platform secrets: passwords/backup codes live in your password manager or vault.
APP_ENV=development
APP_SECRET_KEY={key}
ENVIRONMENT_LABEL={label}
DATABASE_URL=sqlite:///./data/live.db
LOG_DIR=logs/live
REPORTS_DIR=reports/live
HOST=127.0.0.1
PORT=8077
PUBLIC_BASE_URL=http://127.0.0.1:8077
SCHEDULER_ENABLED=true
VAULT_BACKEND=reference_only
VAULT_REF_SCHEMES={schemes}
COMPANY_EMAIL_DOMAINS={domain}
META_INTEGRATION=disabled
META_BUSINESS_ID={business}
NOTIFICATION_BACKEND=none
# Operator-run local proxies (proxy.py on 127.0.0.1) and the approved neutral health-check endpoint
PROXY_CONFIG_FILE=config/proxies.operator-local.json
PROXY_HEALTHCHECK_ALLOWED_URLS=https://example.com/
PROXY_HEALTHCHECK_DEFAULT_URL=https://example.com/
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--meta-business-id", required=True, help="business portfolio ID (not a secret)")
    parser.add_argument(
        "--company-email-domain", "--email-domain", dest="email_domain", default="",
        help="a domain the COMPANY controls (never a consumer domain such as gmail.com); omit if there is none",
    )
    parser.add_argument("--vault-scheme", default="bw", help="prefix you use for vault references, e.g. bw, op, vault")
    parser.add_argument("--candidate-provided", action="store_true", help="resources were created by the candidate, not the company")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    if not re.fullmatch(r"\d{5,25}", args.meta_business_id):
        raise SystemExit("--meta-business-id must be the numeric business portfolio ID")
    domain = args.email_domain.strip().lower()
    if domain and not re.fullmatch(r"[a-z0-9.-]+\.[a-z]{2,}", domain):
        raise SystemExit("--company-email-domain must be a bare domain such as testco.example (not a full address)")
    if domain in CONSUMER_MAIL_DOMAINS:
        raise SystemExit(
            f"{domain} is a consumer mail domain, not a company domain. Omit --company-email-domain and record the "
            "mailbox as personal_provider_substitute in the email task, so the audit reports it honestly."
        )
    if not re.fullmatch(r"[a-z][a-z0-9+.-]{1,20}", args.vault_scheme):
        raise SystemExit("--vault-scheme must be a short lowercase prefix such as bw, op or vault")
    target = Path(".env")
    if target.exists() and not args.force:
        raise SystemExit(".env already exists; use --force to replace it")
    schemes = ",".join(dict.fromkeys([args.vault_scheme, "vault", "op", "bw"]))
    target.write_text(
        TEMPLATE.format(
            key=secrets.token_urlsafe(48),
            label="candidate_provided_test_environment" if args.candidate_provided else "company_test_environment",
            schemes=schemes,
            domain=domain,
            business=args.meta_business_id,
        ),
        encoding="utf-8",
    )
    print("Wrote .env for the live run (secret key generated, not shown).")


if __name__ == "__main__":
    main()
