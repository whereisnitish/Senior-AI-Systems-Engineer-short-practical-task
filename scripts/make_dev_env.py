"""Create .env.demo for the SYNTHETIC demo (development only).

The synthetic demo has its own database, log folder and report folder, so it can
never mix with live data. Use it by setting IOM_ENV_FILE before each command:

    python -m scripts.make_dev_env            # refuses to overwrite an existing .env.demo
    $env:IOM_ENV_FILE=".env.demo"              # PowerShell   (bash: export IOM_ENV_FILE=.env.demo)
    python -m scripts.init_db; python -m scripts.seed_demo --reset; python -m scripts.proxy_demo
"""

from __future__ import annotations

import argparse
import secrets
from pathlib import Path

TEMPLATE = """# SYNTHETIC DEMO CONFIGURATION - generated by scripts/make_dev_env.py. Development only.
# Use with: IOM_ENV_FILE=.env.demo
APP_ENV=development
APP_SECRET_KEY={key}
ENVIRONMENT_LABEL=company_test_environment
DATABASE_URL=sqlite:///./data/demo.db
LOG_DIR=logs/demo
REPORTS_DIR=reports/synthetic_demo
HOST=127.0.0.1
PORT=8077
PUBLIC_BASE_URL=http://127.0.0.1:8077
SCHEDULER_ENABLED=true
VAULT_BACKEND=dev_memory
DEV_VAULT_FILE=data/dev_vault.synthetic.json
COMPANY_EMAIL_DOMAINS=testco.example
META_INTEGRATION=disabled
NOTIFICATION_BACKEND=none
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    target = Path(".env.demo")
    if target.exists() and not args.force:
        raise SystemExit(".env.demo already exists; use --force to replace it")
    target.write_text(TEMPLATE.format(key=secrets.token_urlsafe(48)), encoding="utf-8")
    print("Wrote .env.demo for the synthetic demo (secret key generated, not shown).")
    print('Use it with:  $env:IOM_ENV_FILE=".env.demo"   (bash: export IOM_ENV_FILE=.env.demo)')


if __name__ == "__main__":
    main()
